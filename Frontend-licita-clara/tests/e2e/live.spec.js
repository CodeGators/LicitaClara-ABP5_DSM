import { test, expect } from '@playwright/test'

test('consulta real pelo proxy Vite navega por lista, item, processo e documentos', async ({ page }, testInfo) => {
  await page.addInitScript(() => localStorage.setItem('lc_ajuda_vista', '1'))
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/itens')
  await expect(page.getByRole('heading', { name: 'Consultar itens', exact: true })).toBeVisible()
  const rows = page.locator('section[aria-label="Resultados da consulta"] tbody tr')
  await expect(rows.first()).toBeVisible()
  const base = new URL(page.url()).searchParams.get('base_id')
  expect(base).toMatch(/^[a-f0-9-]{36}$/)
  const initial = await rows.count()
  expect(initial).toBeGreaterThan(0)
  await page.getByLabel('Itens por página', { exact: true }).selectOption('5')
  await page.getByRole('button', { name: 'Aplicar filtros' }).click()
  await expect(rows).toHaveCount(Math.min(initial, 5))
  if (initial > 5) {
    await page.getByRole('button', { name: 'Próxima', exact: true }).click()
    await expect(page).toHaveURL(/pagina=2/)
  }
  await rows.first().getByRole('link').click()
  await expect(page.getByRole('heading', { name: 'Resultados do item', exact: true })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Documentos da compra e contratos vinculados', exact: true })).toBeVisible()
  await expect(page.getByText('Carregando documentos…', { exact: true })).toHaveCount(0)
  await expect(page.getByRole('alert')).toHaveCount(0)
  expect(new URL(page.url()).searchParams.get('base_id')).toBe(base)
  await page.screenshot({ path: testInfo.outputPath('item-real.png'), fullPage: true })
  await page.getByRole('link', { name: 'Ver processo da compra' }).click()
  await expect(page.getByRole('heading', { name: 'Itens deste processo', exact: true })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Documentos da compra e contratos vinculados', exact: true })).toBeVisible()
  expect(new URL(page.url()).searchParams.get('base_id')).toBe(base)
  expect(errors).toEqual([])
})

test('painel, ranking e fornecedores reais reconciliam recorte e conservam a análise na URL', async ({ page }, testInfo) => {
  await page.addInitScript(() => localStorage.setItem('lc_ajuda_vista', '1'))
  const errors=[]; page.on('pageerror',e => errors.push(e.message))
  await page.goto('/painel')
  await expect(page.getByRole('heading',{name:'Painel do recorte'})).toBeVisible()
  await expect(page.locator('.kpi').first()).toBeVisible()
  await expect(page).toHaveURL(/modelo_id=/)
  const selection=new URL(page.url()).searchParams
  const base=selection.get('base_id'), run=selection.get('execucao_id'), model=selection.get('modelo_id')
  const result=await page.request.get('/api/v1/visao/painel',{params:{base_id:base,execucao_id:run,modelo_id:model}})
  expect(result.ok()).toBe(true)
  const snapshot=await result.json()
  expect(snapshot.resumo.analisados+snapshot.resumo.parcial+snapshot.resumo.nao_analisados).toBe(snapshot.resumo.itens)
  expect(snapshot.evolucao.reduce((n,m)=>n+m.itens,0)).toBe(snapshot.resumo.itens)
  await page.screenshot({path:testInfo.outputPath('painel-real.png'),fullPage:true})
  await page.getByRole('link',{name:'Ranking experimental',exact:true}).click()
  await expect(page.getByRole('heading',{name:`${snapshot.resumo.itens} item(ns) no ranking`})).toBeVisible()
  expect(new URL(page.url()).searchParams.get('execucao_id')).toBe(run)
  await page.locator('section.card tbody a.link-a').first().click()
  await expect(page.getByRole('heading',{name:'Análise experimental selecionada'})).toBeVisible()
  await expect(page.getByText('Carregando…',{exact:true})).toHaveCount(0)
  expect(new URL(page.url()).searchParams.get('modelo_id')).toBe(model)
  await page.getByRole('link',{name:'Voltar à consulta'}).click()
  await page.getByRole('link',{name:'Fornecedores',exact:true}).click()
  await expect(page.getByRole('heading',{name:'Fornecedores do recorte'})).toBeVisible()
  await page.locator('section.card tbody a.link-a').first().click()
  await expect(page.getByRole('heading',{name:'Relações do fornecedor'})).toBeInViewport()
  await expect(page.getByRole('heading',{name:'Participação e concentração por órgão'})).toBeVisible()
  await page.screenshot({path:testInfo.outputPath('fornecedor-real.png'),fullPage:true})
  await page.setViewportSize({width:390,height:844})
  await page.goto(`/painel?base_id=${base}&execucao_id=${run}&modelo_id=${model}`)
  await expect(page.locator('.kpi').first()).toBeVisible()
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
  await page.screenshot({path:testInfo.outputPath('painel-real-mobile.png'),fullPage:true})
  expect(errors).toEqual([])
})
