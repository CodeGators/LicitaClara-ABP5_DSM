import { test, expect as playwrightExpect } from '@playwright/test'

const expect = playwrightExpect.configure({ timeout: 20000 })
test.setTimeout(60000)

async function openFirstItem(page) {
  const row = page.locator('.product-table tbody tr').first()
  await expect(row).toBeVisible()
  const summary = row.locator('.product-purchases summary')
  if (await summary.count()) await summary.click()
  await row.getByRole('link').first().click()
  await expect(page.locator('.analysis-detail')).toBeVisible()
}

test('consulta real navega por produto, detalhe e compra usando a mesma base', async ({ page }) => {
  await page.addInitScript(() => localStorage.setItem('lc_ajuda_vista', '1'))
  const errors = []; page.on('pageerror', error => errors.push(error.message))
  await page.goto('/ranking?tamanho_pagina=5')
  await expect(page.getByRole('heading', { name: 'Itens Sinalizados', exact: true })).toBeVisible()
  const rows = page.locator('.product-table tbody tr')
  await expect(rows.first()).toBeVisible()
  const base = new URL(page.url()).searchParams.get('base_id')
  expect(base).toMatch(/^[a-f0-9-]{36}$/)
  expect(await rows.count()).toBeLessThanOrEqual(5)
  const next = page.getByRole('button', { name: 'Próxima', exact: true })
  if (await next.isEnabled()) {
    await next.click()
    await expect(page).toHaveURL(/pagina=2/)
  }
  await openFirstItem(page)
  await expect(page.getByRole('link', { name: 'Gerar relatório da licitação' })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Documentos', exact: true })).toHaveCount(0)
  expect(new URL(page.url()).searchParams.get('base_id')).toBe(base)
  await page.getByRole('link', { name: 'Ver todos os itens da compra' }).click()
  await expect(page.getByRole('heading', { name: 'Itens deste processo' })).toBeVisible()
  await expect(page.getByRole('link', { name: '← Itens Sinalizados' })).toBeVisible()
  expect(new URL(page.url()).searchParams.get('base_id')).toBe(base)
  expect(errors).toEqual([])
})

test('painel, produtos e fornecedores reais conservam a base e a execução publicada', async ({ page }) => {
  await page.addInitScript(() => localStorage.setItem('lc_ajuda_vista', '1'))
  const errors=[]; page.on('pageerror',error => errors.push(error.message))
  await page.goto('/painel')
  await expect(page.getByRole('heading', { name: 'Painel geral', exact: true })).toBeVisible()
  await expect(page.locator('.dashboard-kpis strong').first()).toBeVisible()
  const selection = new URL(page.url()).searchParams
  const base = selection.get('base_id'), execution = selection.get('execucao_id')
  const response = await page.request.get('/api/v1/visao/painel', { params: { base_id: base, execucao_id: execution } })
  expect(response.ok()).toBe(true)
  const snapshot = await response.json()
  expect(snapshot.resumo.analisados + snapshot.resumo.parcial + snapshot.resumo.nao_analisados).toBe(snapshot.resumo.itens)
  await page.getByRole('link', { name: 'Itens Sinalizados', exact: true }).click()
  await expect(page.locator('.product-table tbody tr').first()).toBeVisible()
  expect(new URL(page.url()).searchParams.get('base_id')).toBe(base)
  expect(new URL(page.url()).searchParams.get('execucao_id')).toBe(execution)
  await openFirstItem(page)
  await page.getByRole('link', { name: 'Voltar à consulta' }).click()
  await page.getByRole('link', { name: 'Fornecedores', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Fornecedores', exact: true })).toBeVisible()
  await page.locator('.supplier-main-row .dashboard-analysis-link').first().click()
  await expect(page.getByRole('heading', { name: 'Resumo do fornecedor' })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Participação no gasto por órgão' })).toBeVisible()
  expect(new URL(page.url()).searchParams.get('base_id')).toBe(base)
  expect(errors).toEqual([])
})
