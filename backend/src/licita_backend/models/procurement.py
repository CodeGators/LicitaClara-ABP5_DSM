import sqlalchemy as sa

from licita_backend.models.helpers import (
    MONEY,
    base_fk,
    check,
    json,
    pk,
    ref,
    table,
    text,
    timestamp,
    uid,
    unique,
)

orgaos = table(
    "orgaos",
    "cadastro",
    pk(),
    text("fonte"),
    text("chave_oficial"),
    text("nome"),
    text("cnpj", nullable=True),
    timestamp(),
    unique("fonte", "chave_oficial"),
)
fornecedores = table(
    "fornecedores",
    "cadastro",
    pk(),
    text("fonte"),
    text("tipo_identificacao"),
    text("identificacao"),
    text("nome"),
    timestamp(),
    unique("fonte", "tipo_identificacao", "identificacao"),
)
modalidades = table(
    "modalidades",
    "cadastro",
    pk(),
    text("fonte"),
    text("codigo"),
    text("nome"),
    unique("fonte", "codigo"),
)
itens_catalogo = table(
    "itens_catalogo",
    "cadastro",
    pk(),
    text("catalogo"),
    text("codigo"),
    text("descricao"),
    text("codigo_grupo", nullable=True),
    text("codigo_classe", nullable=True),
    text("codigo_pdm", nullable=True),
    timestamp(),
    unique("catalogo", "codigo"),
)
processos = table(
    "processos",
    "identidade",
    pk(),
    text("fonte"),
    text("chave_oficial"),
    timestamp(),
    unique("fonte", "chave_oficial"),
)
processos_versoes = table(
    "processos_versoes",
    "dados",
    pk(),
    ref("base_id", "versoes_base"),
    ref("processo_id", "processos"),
    ref("orgao_id", "orgaos"),
    ref("modalidade_id", "modalidades", nullable=True),
    text("orgao_nome"),
    text("codigo_unidade"),
    text("nome_unidade", nullable=True),
    text("numero_compra"),
    text("numero_controle_pncp", nullable=True),
    text("numero_processo", nullable=True),
    sa.Column("ano", sa.Integer(), nullable=False),
    text("objeto"),
    text("situacao"),
    sa.Column("data_publicacao", sa.Date(), nullable=True),
    sa.Column("data_abertura", sa.Date(), nullable=True),
    sa.Column("data_resultado", sa.Date(), nullable=True),
    sa.Column("valor_estimado", MONEY, nullable=True),
    sa.Column("valor_homologado", MONEY, nullable=True),
    sa.Column("orcamento_sigiloso", sa.Boolean(), nullable=True),
    json("atributos_origem"),
    timestamp(),
    unique("processo_id", "base_id"),
    unique("id", "base_id"),
    unique("id", "processo_id", "base_id"),
    check("valor_estimado IS NULL OR valor_estimado >= 0", "estimado_nao_negativo"),
    check("valor_homologado IS NULL OR valor_homologado >= 0", "homologado_nao_negativo"),
)
sa.Index(
    "ix_processos_orgao_data_resultado",
    processos_versoes.c.orgao_id,
    processos_versoes.c.data_resultado,
)
sa.Index(
    "ix_processos_base_data_publicacao",
    processos_versoes.c.base_id,
    processos_versoes.c.data_publicacao,
)

itens_processo = table(
    "itens_processo",
    "identidade",
    pk(),
    ref("processo_id", "processos"),
    text("chave_oficial"),
    timestamp(),
    unique("processo_id", "chave_oficial"),
    unique("id", "processo_id"),
)
itens_versoes = table(
    "itens_versoes",
    "dados",
    pk(),
    ref("base_id", "versoes_base"),
    uid("item_id"),
    uid("processo_id"),
    uid("processo_versao_id"),
    ref("catalogo_id", "itens_catalogo", nullable=True),
    text("numero_item"),
    text("descricao"),
    text("unidade_medida", nullable=True),
    sa.Column("quantidade", MONEY, nullable=True),
    sa.Column("valor_unitario_estimado", MONEY, nullable=True),
    sa.Column("orcamento_sigiloso", sa.Boolean(), nullable=True),
    json("atributos_origem"),
    timestamp(),
    unique("item_id", "base_id"),
    unique("id", "base_id"),
    unique("id", "processo_versao_id", "base_id"),
    sa.ForeignKeyConstraint(
        ["item_id", "processo_id"], ["itens_processo.id", "itens_processo.processo_id"]
    ),
    sa.ForeignKeyConstraint(
        ["processo_versao_id", "processo_id", "base_id"],
        ["processos_versoes.id", "processos_versoes.processo_id", "processos_versoes.base_id"],
    ),
    check("quantidade IS NULL OR quantidade >= 0", "quantidade_nao_negativa"),
    check(
        "valor_unitario_estimado IS NULL OR valor_unitario_estimado >= 0", "estimado_nao_negativo"
    ),
)
sa.Index("ix_itens_processo_versao", itens_versoes.c.processo_versao_id)
resultados_itens = table(
    "resultados_itens",
    "dados",
    pk(),
    ref("base_id", "versoes_base"),
    uid("item_versao_id"),
    ref("fornecedor_id", "fornecedores"),
    text("fornecedor_nome"),
    sa.Column("sequencial_resultado", sa.Integer(), nullable=False),
    text("chave_origem"),
    text("situacao"),
    sa.Column("cancelado", sa.Boolean(), nullable=False, server_default=sa.false()),
    sa.Column("quantidade_homologada", MONEY, nullable=True),
    sa.Column("valor_unitario_homologado", MONEY, nullable=True),
    sa.Column("valor_total_homologado", MONEY, nullable=True),
    sa.Column("data_resultado", sa.Date(), nullable=True),
    json("atributos_origem"),
    base_fk("itens_versoes", "item_versao_id"),
    unique("base_id", "item_versao_id", "fornecedor_id", "sequencial_resultado"),
    unique("id", "base_id"),
    check("quantidade_homologada IS NULL OR quantidade_homologada >= 0", "quantidade_nao_negativa"),
    check(
        "valor_unitario_homologado IS NULL OR valor_unitario_homologado >= 0",
        "unitario_nao_negativo",
    ),
    check("valor_total_homologado IS NULL OR valor_total_homologado >= 0", "total_nao_negativo"),
)
sa.Index(
    "ix_resultados_fornecedor_data",
    resultados_itens.c.fornecedor_id,
    resultados_itens.c.data_resultado,
)
referencias_precos = table(
    "referencias_precos",
    "dados",
    pk(),
    ref("base_id", "versoes_base"),
    ref("catalogo_id", "itens_catalogo"),
    ref("fornecedor_id", "fornecedores", nullable=True),
    text("fonte"),
    text("chave_origem"),
    text("id_compra_oficial"),
    text("id_item_oficial"),
    text("descricao"),
    text("unidade_fornecimento", nullable=True),
    text("sigla_unidade_fornecimento", nullable=True),
    sa.Column("capacidade_fornecimento", MONEY, nullable=True),
    text("sigla_medida", nullable=True),
    sa.Column("quantidade", MONEY, nullable=True),
    sa.Column("preco_unitario", MONEY, nullable=False),
    sa.Column("data_compra", sa.Date(), nullable=False),
    json("atributos_origem"),
    unique("base_id", "fonte", "chave_origem"),
    unique("id", "base_id"),
    check("preco_unitario > 0", "preco_positivo"),
    check(
        "capacidade_fornecimento IS NULL OR capacidade_fornecimento >= 0", "capacidade_nao_negativa"
    ),
)
sa.Index(
    "ix_referencias_catalogo_data",
    referencias_precos.c.catalogo_id,
    referencias_precos.c.data_compra,
)
proveniencias_registros = table(
    "proveniencias_registros",
    "dados",
    pk(),
    uid("base_id"),
    uid("importacao_id"),
    text("membro_arquivo"),
    sa.Column("numero_linha", sa.BigInteger(), nullable=False),
    uid("processo_versao_id", nullable=True),
    uid("item_versao_id", nullable=True),
    uid("resultado_item_id", nullable=True),
    uid("referencia_preco_id", nullable=True),
    uid("participacao_id", nullable=True),
    uid("contrato_versao_id", nullable=True),
    uid("contrato_processo_id", nullable=True),
    uid("documento_id", nullable=True),
    sa.ForeignKeyConstraint(
        ["base_id", "importacao_id"], ["base_importacoes.base_id", "base_importacoes.importacao_id"]
    ),
    base_fk("processos_versoes", "processo_versao_id"),
    base_fk("itens_versoes", "item_versao_id"),
    base_fk("resultados_itens", "resultado_item_id"),
    base_fk("referencias_precos", "referencia_preco_id"),
    base_fk("participacoes", "participacao_id"),
    base_fk("contratos_versoes", "contrato_versao_id"),
    base_fk("contratos_processos", "contrato_processo_id"),
    base_fk("documentos", "documento_id"),
    check(
        "num_nonnulls(processo_versao_id, item_versao_id, resultado_item_id, "
        "referencia_preco_id, participacao_id, contrato_versao_id, contrato_processo_id, "
        "documento_id) = 1",
        "um_alvo",
    ),
    check("numero_linha >= 1", "linha_positiva"),
    sa.UniqueConstraint(
        "base_id",
        "importacao_id",
        "membro_arquivo",
        "numero_linha",
        "processo_versao_id",
        "item_versao_id",
        "resultado_item_id",
        "referencia_preco_id",
        "participacao_id",
        "contrato_versao_id",
        "contrato_processo_id",
        "documento_id",
        name="uq_proveniencia_linha_alvo",
        postgresql_nulls_not_distinct=True,
    ),
)
